"""Write an overview of every profile in a Maxroll build guide's planner.

  python profiles_overview.py <guide or planner URL> --char <key>

Writes chars/<key>/profiles.md: per profile (Starter, Midgame, Endgame,
Bossing, Pushing, ...) the item in each slot with its legendary power, sockets
(gems, runes, splinters), tempers, specialization, and the talisman seal and
charms. Use it to check a drop against every setup the guide uses, not only
the profile the filter is built from.
"""
import argparse
import json
import os
import re

from maxroll_import import GAME_DATA, PLANNER_API, fetch, planner_id, prettify_temper

HERE = os.path.dirname(os.path.abspath(__file__))
SLOT_NAMES = {"4": "Helm", "5": "Chest", "13": "Gloves", "14": "Pants", "15": "Boots",
              "18": "Amulet", "16": "Ring 1", "17": "Ring 2", "10": "Ranged",
              "11": "Main hand", "12": "Off-hand", "20": "Seal", "21": "Charm 1",
              "22": "Charm 2", "23": "Charm 3", "24": "Charm 4", "25": "Charm 5",
              "26": "Charm 6"}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("url")
    ap.add_argument("--char", required=True)
    args = ap.parse_args()

    pid = planner_id(args.url)
    planner = json.loads(json.loads(fetch(PLANNER_API + pid, f"planner_{pid}.json"))["data"])
    game = json.loads(fetch(GAME_DATA, "maxroll_game_data.json"))
    enus_path = os.path.join(HERE, ".cache", "maxroll_game_data_enus.json")
    enus = json.load(open(enus_path, encoding="utf-8")) if os.path.exists(enus_path) else {"items": {}, "affixes": {}, "skills": {}}
    by_id = {v["id"]: k for k, v in game["affixes"].items() if isinstance(v, dict)}

    def item_name(k):
        v = enus["items"].get(k)
        return v["name"] if isinstance(v, dict) and v.get("name") else k

    def power_name(nid):
        k = by_id.get(nid)
        v = enus["affixes"].get(k, {}) if k else {}
        name = ((v.get("prefix") or "") + " " + (v.get("suffix") or "")).strip()
        return name or k or str(nid)

    def socket_name(s):
        v = enus["items"].get(s)
        if isinstance(v, dict) and v.get("name"):
            return v["name"]
        return re.sub(r"^(S15_)?(Rune_|SoulSplinter_|Gem_)", "", s).replace("_", " ")

    def spec_name(k):
        v = enus["skills"].get(k) if isinstance(enus.get("skills"), dict) else None
        return (v.get("name") if isinstance(v, dict) else None) or k

    out = [f"# Guide profiles ({args.url})", "",
           f"Planner `{pid}`, game data {game.get('version')}. Generated by `profiles_overview.py`.", ""]
    for prof in planner["profiles"]:
        if not prof.get("items") or prof["name"].startswith("("):
            continue
        out += [f"## {prof['name']}", "", f"Specialization: {spec_name(prof.get('specialization', '?'))}", "",
                "| Slot | Item | Power | Sockets | Temper |", "|---|---|---|---|---|"]
        for slot, idx in sorted(prof["items"].items(), key=lambda kv: int(kv[0])):
            it = planner["items"][str(idx)]
            powers = ", ".join(power_name(a["nid"]) for a in it.get("aspects") or [] if isinstance(a, dict))
            socks = ", ".join(socket_name(s) for s in it.get("sockets") or [])
            temps = ", ".join(prettify_temper(by_id.get(t["nid"], str(t["nid"]))) for t in it.get("tempered", []))
            out.append(f"| {SLOT_NAMES.get(slot, slot)} | {item_name(it['id'])} | {powers} | {socks} | {temps} |")
        out.append("")
    path = os.path.join(HERE, "chars", args.char, "profiles.md")
    open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("Wrote", path)


if __name__ == "__main__":
    main()
